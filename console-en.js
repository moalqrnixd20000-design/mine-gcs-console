(function () {
  var P = window.CanvasRenderingContext2D && CanvasRenderingContext2D.prototype;
  if (!P) return;
  ["fillText", "strokeText"].forEach(function (fn) {
    var draw = P[fn];
    P[fn] = function (text) {
      if (window.PageLang && window.PageLang.get() === "en" && /[؀-ۿ]/.test(String(text))) {
        var args = Array.prototype.slice.call(arguments);
        args[0] = window.PageLang.t(String(text));
        var dir = this.direction;
        this.direction = "ltr";
        var out = draw.apply(this, args);
        this.direction = dir;
        return out;
      }
      return draw.apply(this, arguments);
    };
  });
})();
